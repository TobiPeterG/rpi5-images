def excluded_path(config: ExtkitConfig, relative):
    return any(relative.parts[:len(prefix)] == prefix for prefix in config.excluded_trees)


def relative_path(config: ExtkitConfig, value, kind=None):
    path = Path(value)
    if not path.is_absolute() or ".." in path.parts or len(path.parts) < 3:
        fail(f"expected an absolute file path: {value}")
    relative = path.relative_to("/")
    actual_kind = kind_for(config, relative)
    if kind is not None and actual_kind != kind:
        fail(f"/{relative} belongs to {actual_kind}, not {kind}")
    if relative.parts[:2] in (("usr", "lib"), ("etc", "extension-release.d")) and "extension-release.d" in relative.parts:
        fail("extension-release metadata is generated by this tool")
    if excluded_path(config, relative):
        fail(f"runtime or extension storage cannot be staged: /{relative}")
    return relative


def kind_for(config: ExtkitConfig, relative):
    for kind, prefixes in config.kinds.items():
        if relative.parts[0] in prefixes:
            return kind
    expected = ", ".join(f"/{prefix}" for prefixes in config.kinds.values() for prefix in prefixes)
    fail(f"unsupported extension path: /{relative} (expected {expected})")


def live_file(config: ExtkitConfig, relative):
    path = config.root / relative
    for parent in list(path.parents)[:-1]:
        if parent == config.root:
            break
        if parent.is_symlink():
            fail(f"symlinked parent directory is unsupported: {parent}")
    if not path.is_symlink() and not path.is_file():
        fail(f"live path is missing or has an unsupported file type: /{relative}")
    return path


def upper_candidates(config: ExtkitConfig, relative):
    visible = Path("/") / relative
    for upper, root_prefix in config.overlay_uppers:
        try:
            suffix = visible.relative_to(root_prefix)
        except ValueError:
            continue
        yield upper / suffix


def is_whiteout(config: ExtkitConfig, relative):
    for candidate in upper_candidates(config, relative):
        try:
            info = candidate.lstat()
        except FileNotFoundError:
            continue
        if stat.S_ISCHR(info.st_mode) and info.st_rdev == os.makedev(0, 0):
            return True
        if stat.S_ISREG(info.st_mode) and info.st_size == 0:
            try:
                if os.getxattr(candidate, "trusted.overlay.whiteout"):
                    return True
            except OSError:
                pass
    return False


@contextmanager
def base_tree(config: ExtkitConfig):
    if config.base_directory:
        if not config.base_directory.is_dir():
            fail(f"base directory is not accessible: {config.base_directory}")
        yield config.base_directory
        return
    with tempfile.TemporaryDirectory(prefix="extension-base-", dir=config.runtime_directory) as directory:
        process.run(["mount", "-t", config.base_fstype, "-o", "ro,nodev,nosuid,noexec", str(config.base_device), directory], check=True)
        try:
            yield Path(directory)
        finally:
            process.run(["umount", directory], check=True)


def changed_paths(config: ExtkitConfig, kind=None):
    wanted = set(config.kinds[kind]) if kind else {prefix for prefixes in config.kinds.values() for prefix in prefixes}
    changed = set()
    accessible = False
    for upper, root_prefix in config.overlay_uppers:
        if not upper.is_dir():
            continue
        accessible = True
        for directory, names, files in os.walk(upper, followlinks=False):
            for name in sorted(names + files):
                candidate = Path(directory) / name
                if candidate.is_dir() and not candidate.is_symlink():
                    continue
                visible = root_prefix / candidate.relative_to(upper)
                relative = visible.relative_to("/") if visible.is_absolute() else visible
                if relative.parts and relative.parts[0] in wanted and not excluded_path(config, relative):
                    changed.add("/" + str(relative))
    if not accessible:
        configured = ", ".join(str(upper) for upper, _ in config.overlay_uppers)
        fail(f"no configured overlay upperdir is accessible: {configured}")
    return sorted(changed)


def normalize_shell_glob(patterns):
    """Recognize an unquoted '*' after the shell expanded it in the current directory."""
    expanded = glob.glob("*")
    if patterns and len(patterns) == len(expanded) and set(patterns) == set(expanded):
        return ["*"]
    return patterns


def select_paths(patterns, candidates, description):
    patterns = normalize_shell_glob(patterns)
    if not patterns or patterns == ["*"]:
        return sorted(candidates)
    selected = set()
    for value in patterns:
        if value == "*":
            selected.update(candidates)
            continue
        if value.startswith("/"):
            pattern = value
            matches = [path for path in candidates if fnmatch.fnmatchcase(path, pattern)]
        else:
            # An unquoted shell glob turns '*' into top-level names.
            # Treat relative selectors as subtrees.
            prefix = "/" + value.strip("/")
            matches = [path for path in candidates
                       if path == prefix or path.startswith(prefix + "/")]
        selected.update(matches)
    if not selected:
        fail(f"no {description} files match: {' '.join(patterns)}")
    return sorted(selected)


def copy_selected(source, destination):
    """Copy bytes, then ownership, then final metadata."""
    source, destination = Path(source), Path(destination)
    info = source.lstat()
    attributes = {name: os.getxattr(source, name, follow_symlinks=False)
                  for name in os.listxattr(source, follow_symlinks=False)
                  if not name.startswith(('trusted.overlay.', 'user.overlay.'))}
    remove_path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    symlink = stat.S_ISLNK(info.st_mode)
    if symlink:
        destination.symlink_to(os.readlink(source))
    else:
        shutil.copyfile(source, destination, follow_symlinks=False)
    try:
        if os.geteuid() == 0:
            os.chown(destination, info.st_uid, info.st_gid, follow_symlinks=False)
        for name in os.listxattr(destination, follow_symlinks=False):
            if name not in attributes and not name.startswith(('trusted.overlay.', 'user.overlay.')):
                os.removexattr(destination, name, follow_symlinks=False)
        if not symlink:
            os.chmod(destination, stat.S_IMODE(info.st_mode))
        os.utime(destination, ns=(info.st_atime_ns, info.st_mtime_ns), follow_symlinks=False)
        # chown can clear set-id bits and capabilities.
        for name, value in attributes.items():
            os.setxattr(destination, name, value, follow_symlinks=False)
        copied = destination.lstat()
        if ((copied.st_uid, copied.st_gid, stat.S_IMODE(copied.st_mode)) !=
                (info.st_uid, info.st_gid, stat.S_IMODE(info.st_mode))):
            fail(f'cannot preserve ownership/permissions of {source}')
        if any(os.getxattr(destination, name, follow_symlinks=False) != value
               for name, value in attributes.items()):
            fail(f'cannot preserve extended attributes of {source}')
    except (OSError, NotImplementedError) as error:
        fail(f'cannot preserve metadata of {source}: {error}')


def remove_path(path):
    if path.is_symlink() or (path.exists() and not path.is_dir()):
        path.unlink()
    elif path.is_dir():
        shutil.rmtree(path)
